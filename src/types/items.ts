export type ItemCategory =
  | 'tool'
  | 'seed'
  | 'crop'
  | 'forage'
  | 'material'
  | 'fish'
  | 'bug'
  | 'furniture'
  | 'food'
  | 'collectible';

export type ItemRarity = 'common' | 'uncommon' | 'rare' | 'legendary';

export type ToolType = 'hoe' | 'watering_can' | 'axe' | 'pickaxe' | 'fishing_rod' | 'bug_net';

export type ToolTier = 'basic' | 'copper' | 'iron' | 'gold';

export interface ItemDefinition {
  id: string;
  name: string;
  description: string;
  category: ItemCategory;
  buyPrice?: number;
  sellPrice: number;
  stackable: boolean;
  maxStack: number;
  rarity: ItemRarity;
  textureKey: string;
  toolType?: ToolType;
  toolTier?: ToolTier;
  energyBonus?: number;
  furnitureKey?: string;
  furnitureSize?: { width: number; height: number };
}

export interface InventorySlot {
  slotIndex: number;
  item: ItemDefinition | null;
  quantity: number;
  quality?: 'normal' | 'silver' | 'gold' | 'iridium';
}

